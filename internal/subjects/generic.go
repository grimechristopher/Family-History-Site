package subjects

// GenericCoupleQuestions are asked about every great-grandparent couple.
//
// The prompts file covers these generations as surname lines rather than as
// people — "the Aldermans were immigrants from Sweden" — so the couples themselves
// arrived with nothing to answer. These give each pair a starting point, phrased
// for someone who never met them and is repeating what they were told.
var GenericCoupleQuestions = []string{
	"What do you know about them? Where did they live, and what did they do?",
	"What's the one story you remember being told about them?",
	"Who told you about them — your parents, or your grandparents?",
	"Are there any photos, objects or heirlooms connected to them?",
	"Do you know where they came from, or why they moved?",
}
